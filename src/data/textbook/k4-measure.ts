工場の流量計で古くから使われてきたのは、管を絞って圧力差を測る**差圧式**です。ほかにも、テーパ管の中で浮き子が浮く高さで読む**面積式**、流れの中に置いた柱の後ろにできる渦の数を数える**渦式**があります。蒸気の流量計には渦式がよく使われます。

どの方式にも、**流量と何が比例するか**という性格があります。差圧式は差圧の平方根、渦式は渦の周波数に比例です。この性格が、測れる範囲の広さや計算の形を決めます。

